export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((product) => product.slug === slug)
}

/** Sản phẩm liên quan: cùng nhu cầu sử dụng, nếu thiếu thì bù bằng cùng thương hiệu */
export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const sameUseCase = PRODUCTS.filter(
    (item) => item.id !== product.id && item.useCase === product.useCase,
  )
  const sameBrand = PRODUCTS.filter(
    (item) =>
      item.id !== product.id &&
      item.brand === product.brand &&
      !sameUseCase.includes(item),
  )
  return [...sameUseCase, ...sameBrand].slice(0, limit)
}

export function getDiscountedProducts(limit = 4): Product[] {
  return PRODUCTS.filter((product) => product.compareAtPrice).slice(0, limit)
}

