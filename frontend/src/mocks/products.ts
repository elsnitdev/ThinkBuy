/** Sinh biến thể cấu hình từ giá gốc */
function buildVariants(
  baseId: number,
  skuPrefix: string,
  configs: { label: string; delta: number; stock: number }[],
  price: number,
  compareAtPrice: number | null,
): ProductVariant[] {
  return configs.map((config, index) => ({
    id: baseId * 100 + index,
    sku: `${skuPrefix}-${config.label.replace(/[^0-9A-Za-z]/g, '')}`,
    label: config.label,
    price: price + config.delta,
    compareAtPrice: compareAtPrice ? compareAtPrice + config.delta : null,
    stock: config.stock,
  }))
}

